------------------------------------------------------------
-- Hot loop: compiled traces against the interpreter and the golden sum
------------------------------------------------------------
local function hot(n)
    local sin, cos, log, atan2 = math.sin, math.cos, math.log, math.atan2
    local s = 0.0
    for i = 1, n do
        local x = i * 1e-3
        s = s + sin(x) + cos(x * 0.7) + x ^ 1.7 + log(x) + atan2(x, 3)
    end
    return s
end

local hot_n = 3000000
local hot_golden = "426a5a4f42440564"
print("\nHot loop")
if jit then
    jit.off()
    jit.flush()
    local interp = hot(hot_n)
    jit.on()
    local traces = 0
    local function onTrace(what) if what == "stop" then traces = traces + 1 end end
    jit.attach(onTrace, "trace")
    local compiled = hot(hot_n)
    jit.attach(onTrace)
    check("the hot loop compiled", traces > 0, "no trace finished")
    check("compiled sum equals interpreted sum", same(interp, compiled),
        bits(interp) .. " vs " .. bits(compiled))
    check("interpreted sum is golden", bits(interp) == hot_golden, bits(interp))
    check("compiled sum is golden", bits(compiled) == hot_golden, bits(compiled))
else
    local s = hot(hot_n)
    check("sum is golden", bits(s) == hot_golden, bits(s))
end

