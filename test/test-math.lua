-- Park-Miller, exact in doubles and in 5.3+ integers alike. Inputs are
-- built from it with exact arithmetic only, so they do not depend on the
-- maths under test.
local seed = 12345
local function u()
    seed = (seed * 16807) % 2147483647
    return seed / 2147483647
end

local p2 = {[0] = 1.0}
for e = 1, 1023 do p2[e] = p2[e - 1] * 2 end
for e = -1, -1074, -1 do p2[e] = p2[e + 1] / 2 end

-- (1 + u) * 2^e with e uniform in [lo, hi), so log-uniform in magnitude.
local function logu(lo, hi)
    local e = lo + math.floor(u() * (hi - lo))
    return (1 + u()) * p2[e]
end

local function signed(x)
    if u() < 0.5 then return -x end
    return x
end

local function spread(name)
    local a, b = u(), u()
    if name == "sin" or name == "cos" or name == "tan" then
        if a < 0.6 then return b * 100 - 50, 0 end
        return signed(logu(-10, 54)), 0
    elseif name == "asin" or name == "acos" then return b * 2 - 1, 0
    elseif name == "atan" then return signed(logu(-14, 27)), 0
    elseif name == "atan2" then return a * 20 - 10, b * 20 - 10
    elseif name == "sinh" or name == "cosh" or name == "tanh" then return a * 60 - 30, 0
    elseif name == "exp" then return (b - 0.5) * (a < 0.5 and 20 or 1450), 0
    elseif name == "log" or name == "log2" or name == "log10" then
        if a < 0.4 then return 0.5 + b * 1.5, 0 end
        return logu(-1000, 1000), 0
    elseif name == "pow" or name == "^" then return logu(-10, 10), b * 60 - 30
    elseif name == "fmod" then return signed(logu(-17, 40)), logu(-10, 10)
    elseif name == "logBase" then return logu(-33, 33), 0.1 + b * 20
    end
end

local inputs = {}
for _, name in ipairs(order) do
    local xs, ys = {}, {}
    for i, p in ipairs(hard[hardSet[name]]) do
        xs[i], ys[i] = num(p[1]), num(p[2])
    end
    for _ = 1, 400 - #xs do
        local x, y = spread(name)
        xs[#xs + 1], ys[#ys + 1] = x, y
    end
    inputs[name] = {xs, ys}
end

------------------------------------------------------------
-- Lua against Zig, interpreted and compiled
------------------------------------------------------------
local function evaluate(f, xs, ys)
    local out = {}
    for i = 1, #xs do out[i] = f(xs[i], ys[i]) end
    return out
end

local function compare(mode)
    for _, name in ipairs(order) do
        local f, zig = F[name][1], F[name][2]
        local xs, ys = inputs[name][1], inputs[name][2]
        local out = evaluate(f, xs, ys)
        local bad
        for i = 1, #xs do
            if not same(out[i], call(zig, xs[i], ys[i])) then bad = i break end
        end
        check(string.format("%s: %s matches Zig on %d inputs", mode, name, #xs), bad == nil,
            bad and string.format("x=%s y=%s lua=%s zig=%s", bits(xs[bad]), bits(ys[bad]),
                bits(out[bad]), bits(call(zig, xs[bad], ys[bad]))))
    end
end

print("Lua against Zig")
if jit then
    jit.off()
    jit.flush()
    compare("interpreter")
    jit.on()
    compare("jit")
else
    compare(_VERSION)
end

